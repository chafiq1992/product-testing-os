const dictionary = new Map(rows.map(([key, fr, ar]) => [key, { fr, ar }]));
const patterns = rows
  .filter(([key]) => /\{value\d+\}/.test(key))
  .sort(
    ([a], [b]) =>
      b.replace(/\{value\d+\}/g, "").length -
      a.replace(/\{value\d+\}/g, "").length,
  )
  .map(([key, fr, ar]) => {
    const names: string[] = key.match(/\{value\d+\}/g) || [];
    const escaped = key
      .split(/\{value\d+\}/)
      .map((part) => part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"));
    return {
      regex: new RegExp("^" + escaped.join("(.+?)") + "$"),
      names,
      fr,
      ar,
    };
  });
export function translate(text: string, language: AffiliateLanguage): string {
  if (!text) return text;
  if (language === "en") return englishDeliveryStates[text] || text;
  if (text !== text.trim())
    return text.replace(text.trim(), translate(text.trim(), language));
  const direct = dictionary.get(text);
  if (direct) return direct[language];
  for (const pattern of patterns) {
    const matches = pattern.regex.exec(text);
    if (matches)
      return pattern[language].replace(
        /\{value\d+\}/g,
        (key) => matches[pattern.names.indexOf(key) + 1],
      );
  }
  return text;
}
